import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';

test('knowledge publishing, personal draft, versions and protected attachments work on this viewport', async ({ page }, info) => {
  if (!process.env.ADMIN_EMAIL || !process.env.ADMIN_PASSWORD_FILE) throw new Error('Development administrator required');
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error' && /^(RangeError|TypeError|Error):/.test(message.text())) errors.push(message.text()); });
  const tag = randomUUID().replaceAll('-', '').slice(0, 8), title = `Инструкция ${tag}`;
  await page.goto('/');
  await page.getByLabel('Рабочая почта').fill(process.env.ADMIN_EMAIL);
  await page.getByLabel('Пароль', { exact: true }).fill(readFileSync(process.env.ADMIN_PASSWORD_FILE, 'utf8').trim());
  await page.getByRole('button', { name: 'Войти в рабочее пространство' }).click();
  await expect(page.getByRole('heading', { name: 'Рабочий стол', exact: true })).toBeVisible();
  if (info.project.name === 'mobile') await page.getByRole('button', { name: 'Открыть меню', exact: true }).click();
  await page.getByRole('link', { name: 'База знаний', exact: true }).click();
  await page.getByRole('button', { name: 'Создать пространство', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Название', { exact: true }).fill(`Знания ${tag}`);
  await dialog.getByLabel('Ключ', { exact: true }).fill(`K${tag}`);
  await dialog.getByRole('button', { name: 'Создать пространство', exact: true }).click();
  await expect(page.getByRole('heading', { name: `Знания ${tag}`, exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Создать страницу', exact: true }).first().click();
  await dialog.getByLabel('Название страницы', { exact: true }).fill(title);
  await dialog.getByRole('button', { name: 'Создать страницу', exact: true }).click();
  const content = page.getByRole('textbox', { name: 'Содержимое страницы', exact: true });
  await content.fill('Первая опубликованная инструкция команды');
  await page.getByRole('button', { name: 'Опубликовать', exact: true }).click();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await expect(page.getByRole('textbox', { name: 'Опубликованная страница' })).toContainText('Первая опубликованная инструкция команды');
  await page.getByRole('button', { name: 'Редактировать страницу', exact: true }).click();
  await content.fill('Вторая редакция с сохранённым личным черновиком');
  await page.getByRole('button', { name: 'Сохранить черновик и закрыть', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Продолжить черновик', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Продолжить черновик', exact: true }).click();
  await expect(content).toContainText('Вторая редакция с сохранённым личным черновиком');
  await page.getByRole('button', { name: 'Опубликовать', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Опубликованная страница' })).toContainText('Вторая редакция с сохранённым личным черновиком');
  await page.getByRole('button', { name: 'История версий', exact: true }).click();
  await expect(dialog.getByText('Версия 1', { exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Восстановить', exact: true }).last().click();
  await expect(page.getByRole('textbox', { name: 'Опубликованная страница' })).toContainText('Первая опубликованная инструкция команды');
  const filename = `instruction-${tag}.txt`, bytes = Buffer.from('Ventilyator protected local attachment');
  await page.getByLabel('Прикрепить файл', { exact: true }).setInputFiles({ name: filename, mimeType: 'text/plain', buffer: bytes });
  await expect(page.getByText(filename, { exact: true })).toBeVisible();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('link', { name: `Скачать ${filename}`, exact: true }).click();
  const download = await downloadEvent; const path = info.outputPath(filename); await download.saveAs(path);
  expect(readFileSync(path).equals(bytes)).toBe(true);
  await page.getByLabel('Комментарий к странице', { exact: true }).fill('Проверено через браузер');
  await page.getByRole('button', { name: 'Отправить комментарий', exact: true }).click();
  await expect(page.getByText('Проверено через браузер', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Редактировать страницу', exact: true }).click();
  await page.getByLabel('Импорт Markdown', { exact: true }).setInputFiles({ name: 'guide.md', mimeType: 'text/markdown', buffer: Buffer.from('# Проверка форматирования\n\n**Важная инструкция**\n\n| Отдел | Действие |\n| --- | --- |\n| Команда | Проверить |\n\n- [ ] Проверить результат') });
  await expect(page.getByRole('columnheader', { name: 'Отдел', exact: true })).toBeVisible();
  const picture = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j5f8AAAAASUVORK5CYII=', 'base64');
  await page.getByLabel('Прикрепить файл', { exact: true }).setInputFiles({ name: `picture-${tag}.png`, mimeType: 'image/png', buffer: picture });
  await page.getByRole('button', { name: 'Вставить в страницу', exact: true }).click();
  await expect(content.locator('img')).toHaveCount(1);
  await page.getByRole('button', { name: 'Опубликовать', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Опубликованная страница' }).locator('img')).toHaveCount(1);
  await expect(page.getByRole('columnheader', { name: 'Отдел', exact: true })).toBeVisible();
  await page.getByText('Оглавление', { exact: true }).click();
  await expect(page.getByRole('link', { name: 'Проверка форматирования', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.reload();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await expect(page.getByRole('textbox', { name: 'Опубликованная страница' }).locator('img')).toHaveCount(1);
  await expect(page.getByRole('columnheader', { name: 'Отдел', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
  await page.screenshot({ path: info.outputPath('knowledge.png'), fullPage: true });
});
